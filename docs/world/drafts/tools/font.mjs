const MARK = { acute: [[3, -2], [2, -1]], grave: [[1, -2], [2, -1]], circ: [[2, -2], [1, -1], [3, -1]], uml: [[1, -1], [3, -1]], cedil: [[2, 7], [1, 8]] };

/** Measure text width in pixels at scale s. */
export const textWidth = (str, s = 1) => [...str.replace(/[Œœ]/g, 'OE')].length * 6 * s - s;

/** Draw text into an RGB buffer. (x, y) = top-left of the cap height. halo = outline colour or null. */
export function drawText(img, W, H, str, x, y, s, color, halo) {
  const plot = (px, py, c) => {
    if (px < 0 || py < 0 || px >= W || py >= H) return;
    const o = (py * W + px) * 3; img[o] = c[0]; img[o + 1] = c[1]; img[o + 2] = c[2];
  };
  const pixels = [];
  let cx = x;
  for (let ch of str.toUpperCase().replace(/Œ/g, 'OE')) {
    let mark = null;
    if (ACC[ch]) { mark = ACC[ch][1]; ch = ACC[ch][0]; }
    const g = G[ch] || G[' '];
    for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) if (g[r][c] === '1') pixels.push([cx + c * s, y + r * s]);
    if (mark && MARK[mark]) for (const [c, r] of MARK[mark]) pixels.push([cx + c * s, y + r * s]);
    cx += 6 * s;
  }
  if (halo) for (const [px, py] of pixels) for (let dy = -1; dy <= s; dy++) for (let dx = -1; dx <= s; dx++) plot(px + dx, py + dy, halo);
  for (const [px, py] of pixels) for (let dy = 0; dy < s; dy++) for (let dx = 0; dx < s; dx++) plot(px + dx, py + dy, color);
}
